#!/usr/bin/env python3
"""
Emit fs.inc for an in-kernel RW virtual filesystem.

Record layout (FS_REC_SIZE = 68 bytes):
    db  56 bytes  null-padded absolute path  (empty path => free slot)
    dd  type      0=dir 1=file 2=exec
    dd  data      pointer to mutable buffer  (0 for dirs)
    dd  size      bytes currently used in buffer

Each non-dir entry owns a FS_CAPACITY-byte buffer in the kernel image.
For real files, the buffer is `incbin + zero pad`. For exec entries and
spare slots, the buffer is zero-padded. Writes mutate the buffer; size
in the entry tracks valid bytes.
"""
import os, sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else "."
OUT  = sys.argv[2] if len(sys.argv) > 2 else "fs.inc"

NAME_LEN  = 56
CAPACITY  = 1024
SPARE     = 16   # free slots for runtime-created files

default_dirs = ["/", "/bin", "/proc", "/var", "/var/log", "/usr","/dev","/lib","/etc"]
scan = [("bin", "exec"), ("proc", "file"), ("var/log", "file"),
        ("usr","file"), ("dev","file"), ("lib","file"), ("etc","file")]

entries = []   # (vpath, kind, host_path|None)
for d in default_dirs:
    entries.append((d, "dir", None))

for top, kind in scan:
    base = os.path.join(ROOT, top)
    if not os.path.isdir(base):
        continue
    for name in sorted(os.listdir(base)):
        host = os.path.join(base, name)
        if not os.path.isfile(host):
            continue
        sz = os.path.getsize(host)
        if sz > CAPACITY:
            sys.exit(f"file too large for FS_CAPACITY={CAPACITY}: {host} ({sz} bytes)")
        entries.append(("/" + top + "/" + name, kind, host))

def emit_path(f, s):
    if len(s) >= NAME_LEN:
        sys.exit(f"path too long ({len(s)} >= {NAME_LEN}): {s}")
    f.write(f'    db "{s}",0\n')
    pad = NAME_LEN - len(s) - 1
    if pad:
        f.write(f'    times {pad} db 0\n')

with open(OUT, "w") as f:
    f.write("; auto-generated by gen_fs.py — do not edit\n\n")
    f.write(f"FS_REC_SIZE      equ 68\n")
    f.write(f"FS_NAME_LEN      equ {NAME_LEN}\n")
    f.write(f"FS_CAPACITY      equ {CAPACITY}\n")
    f.write(f"FS_SPARE_COUNT   equ {SPARE}\n\n")

    # ---- entries table ----
    f.write("fs_entries:\n")
    blob = 0
    for vpath, kind, host in entries:
        emit_path(f, vpath)
        if kind == "dir":
            f.write("    dd 0\n    dd 0\n    dd 0\n")
        else:
            t = 1 if kind == "file" else 2
            sz = os.path.getsize(host)
            f.write(f"    dd {t}\n")
            f.write(f"    dd fs_buf_{blob}\n")
            f.write(f"    dd {sz}\n")
            blob += 1

    # free slots — empty path, type=0, but each has its own buffer
    for i in range(SPARE):
        emit_path(f, "")
        f.write(f"    dd 0\n")
        f.write(f"    dd fs_spare_{i}\n")
        f.write(f"    dd 0\n")

    f.write("fs_entries_end:\n")
    f.write("FS_COUNT  equ ((fs_entries_end - fs_entries) / FS_REC_SIZE)\n\n")

    # ---- file/exec buffers: incbin + zero pad to FS_CAPACITY ----
    blob = 0
    for vpath, kind, host in entries:
        if kind == "dir":
            continue
        rel = os.path.relpath(host, ROOT)
        sz  = os.path.getsize(host)
        f.write(f"fs_buf_{blob}:\n")
        if sz > 0:
            f.write(f'    incbin "{rel}"\n')
        pad = CAPACITY - sz
        if pad > 0:
            f.write(f"    times {pad} db 0\n")
        blob += 1

    # ---- spare buffers: pure zero ----
    for i in range(SPARE):
        f.write(f"fs_spare_{i}:\n")
        f.write(f"    times {CAPACITY} db 0\n")
